@Composable
fun SudokuScreen(
    gameId: String,
    sessionConfig: GameSessionConfig,
    isFavorite: Boolean,
    onToggleFavorite: () -> Unit,
    onRecordOutcome: (MatchOutcome, String, String, Int, Int) -> Unit,
    onPlayCue: (SoundCue) -> Unit,
    onBack: () -> Unit
) {
    val isKiller = gameId == "killer_sudoku"
    val game = remember(gameId) { GameCatalog.byId(gameId) }
    var generated by remember(gameId, sessionConfig.ruleVariant) {
        mutableStateOf(SudokuGenerator.generate(sessionConfig.ruleVariant, isKiller = isKiller))
    }

    var board by remember(generated) {
        mutableStateOf(generated.puzzle.map { it.toList() })
    }
    var notes by remember(generated) {
        mutableStateOf(List(9) { List(9) { emptySet<Int>() } })
    }
    val undoStack = remember { mutableStateListOf<Pair<List<List<Int>>, List<List<Set<Int>>>>>() }
    var selectedCell by remember { mutableStateOf<Pair<Int, Int>?>(null) }
    var noteMode by remember { mutableStateOf(false) }
    var isPaused by remember { mutableStateOf(false) }
    var mistakes by remember { mutableIntStateOf(0) }
    var errorShakeCount by remember { mutableIntStateOf(0) }
    var hintsUsed by remember { mutableIntStateOf(0) }
    var elapsedSeconds by remember { mutableIntStateOf(0) }
    var solved by remember { mutableStateOf(false) }
    var outcomeRecorded by remember { mutableStateOf(false) }

    val cageByCell = remember(generated) {
        val map = mutableMapOf<Pair<Int, Int>, KillerCage>()
        generated.cages.forEach { cage ->
            cage.cells.forEach { cell -> map[cell] = cage }
        }
        map
    }
    val cageLabelCell = remember(generated) {
        generated.cages.associate { cage ->
            val topLeft = cage.cells.minWith(compareBy<Pair<Int, Int>> { it.first }.thenBy { it.second })
            topLeft to cage.targetSum
        }
    }

    LaunchedEffect(isPaused, solved) {
        while (!isPaused && !solved) {
            delay(1000L)
            elapsedSeconds++
        }
    }

    LaunchedEffect(board) {
        val complete = (0..8).all { r -> (0..8).all { c -> board[r][c] == generated.solution[r][c] } }
        if (complete && !solved) {
            solved = true
            if (!outcomeRecorded) {
                outcomeRecorded = true
                onPlayCue(SoundCue.WIN)
                val score = (1000 - mistakes * 75 - hintsUsed * 100 - elapsedSeconds / 3).coerceAtLeast(100)
                onRecordOutcome(
                    MatchOutcome.WIN,
                    "Player 1",
                    "Solved ${sessionConfig.ruleVariant} in ${elapsedSeconds}s ($mistakes mistakes)",
                    score,
                    elapsedSeconds
                )
            }
        }
    }

    fun placeDigit(digit: Int) {
        val (r, c) = selectedCell ?: return
        if (generated.puzzle[r][c] != 0 || solved || isPaused) return
        undoStack.add(board to notes)
        if (noteMode) {
            val updatedRow = notes[r].toMutableList()
            val cur = updatedRow[c]
            updatedRow[c] = if (digit in cur) cur - digit else cur + digit
            notes = notes.toMutableList().apply { this[r] = updatedRow.toList() }
            onPlayCue(SoundCue.KEY_TICK)
        } else {
            val updatedBoard = board.map { it.toMutableList() }
            updatedBoard[r][c] = digit
            board = updatedBoard.map { it.toList() }
            if (digit != generated.solution[r][c]) {
                mistakes++
                errorShakeCount++
                onPlayCue(SoundCue.ERROR)
            } else {
                // Clear matching notes in row/col/box
                val nextNotes = notes.map { it.toMutableList() }
                for (i in 0..8) {
                    nextNotes[r][i] = nextNotes[r][i] - digit
                    nextNotes[i][c] = nextNotes[i][c] - digit
                }
                nextNotes[r][c] = emptySet()
                notes = nextNotes.map { it.toList() }
                val rowDone = (0..8).all { col -> updatedBoard[r][col] == generated.solution[r][col] }
                val colDone = (0..8).all { row -> updatedBoard[row][c] == generated.solution[row][c] }
                val br = (r / 3) * 3
                val bc = (c / 3) * 3
                val boxDone = (br until br + 3).all { rr -> (bc until bc + 3).all { cc -> updatedBoard[rr][cc] == generated.solution[rr][cc] } }
                onPlayCue(if (rowDone || colDone || boxDone) SoundCue.TILE_MERGE else SoundCue.KEY_TICK)
            }
        }
    }

    fun eraseCell() {
        val (r, c) = selectedCell ?: return
        if (generated.puzzle[r][c] != 0 || solved || isPaused) return
        undoStack.add(board to notes)
        val updatedBoard = board.map { it.toMutableList() }
        updatedBoard[r][c] = 0
        board = updatedBoard.map { it.toList() }
        val updatedNotes = notes.map { it.toMutableList() }
        updatedNotes[r][c] = emptySet()
        notes = updatedNotes.map { it.toList() }
        onPlayCue(SoundCue.WOOD_TAP)
    }

    fun applyHint() {
        if (solved || isPaused) return
        val target = selectedCell?.takeIf { (r, c) -> board[r][c] != generated.solution[r][c] }
            ?: run {
                val empties = mutableListOf<Pair<Int, Int>>()
                for (r in 0..8) for (c in 0..8) if (board[r][c] != generated.solution[r][c]) empties.add(r to c)
                empties.randomOrNull()
            } ?: return
        undoStack.add(board to notes)
        val updated = board.map { it.toMutableList() }
        updated[target.first][target.second] = generated.solution[target.first][target.second]
        board = updated.map { it.toList() }
        selectedCell = target
        hintsUsed++
        onPlayCue(SoundCue.HINT)
    }

    fun restart() {
        generated = SudokuGenerator.generate(sessionConfig.ruleVariant, isKiller = isKiller)
        board = generated.puzzle.map { it.toList() }
        notes = List(9) { List(9) { emptySet() } }
        undoStack.clear()
        selectedCell = null
        mistakes = 0
        hintsUsed = 0
        elapsedSeconds = 0
        solved = false
        isPaused = false
        outcomeRecorded = false
    }

    GameScaffold(
        game = game,
        subtitle = "${sessionConfig.ruleVariant} • Mistakes: $mistakes",
        isFavorite = isFavorite,
        canUndo = undoStack.isNotEmpty() && !isPaused,
        onBack = onBack,
        onToggleFavorite = onToggleFavorite,
        onUndo = {
            if (undoStack.isNotEmpty() && !isPaused) {
                val prev = undoStack.removeAt(undoStack.lastIndex)
                board = prev.first
                notes = prev.second
            }
        },
        onRestart = ::restart
    ) {
        // Status Bar: Timer, Mistakes, Pause
        MonoCard(elevated = true) {
            Row(
                modifier = Modifier
                    .fillMaxWidth()
                    .padding(horizontal = 14.dp, vertical = 8.dp),
                horizontalArrangement = Arrangement.SpaceBetween,
                verticalAlignment = Alignment.CenterVertically
            ) {
                Text(
                    text = "%02d:%02d".format(elapsedSeconds / 60, elapsedSeconds % 60),
                    style = MaterialTheme.typography.titleMedium.copy(fontFamily = JetBrainsMonoFontFamily)
                )
                Text(
                    text = "Mistakes: $mistakes",
                    style = MaterialTheme.typography.bodyMedium,
                    color = if (mistakes > 0) MaterialTheme.colorScheme.error else MaterialTheme.colorScheme.onSurfaceVariant
                )
                OutlinedButton(
                    onClick = { isPaused = !isPaused },
                    shape = RoundedCornerShape(10.dp)
                ) {
                    Icon(
                        imageVector = if (isPaused) Icons.Rounded.PlayArrow else Icons.Rounded.Pause,
                        contentDescription = if (isPaused) "Resume" else "Pause",
                        modifier = Modifier.size(16.dp)
                    )
                    Spacer(Modifier.width(4.dp))
                    Text(if (isPaused) "Resume" else "Pause", style = MaterialTheme.typography.labelLarge)
                }
            }
        }

        Spacer(modifier = Modifier.height(10.dp))

        // Sudoku Grid
        BoxWithConstraints(
            modifier = Modifier
                .fillMaxWidth()
                .weight(1f),
            contentAlignment = Alignment.Center
        ) {
            val gridSize = minOf(maxWidth, maxHeight)
            Surface(
                modifier = Modifier
                    .size(gridSize)
                    .shakeOnTrigger(errorShakeCount),
                shape = RoundedCornerShape(8.dp),
                color = MaterialTheme.colorScheme.surface,
                border = BorderStroke(2.dp, MaterialTheme.colorScheme.primary)
            ) {
                if (isPaused) {
                    Box(modifier = Modifier.fillMaxSize(), contentAlignment = Alignment.Center) {
                        Column(horizontalAlignment = Alignment.CenterHorizontally) {
                            Text("GAME PAUSED", style = MaterialTheme.typography.headlineMedium)
                            Spacer(Modifier.height(6.dp))
                            Text(
                                "Board hidden while timer is paused",
                                style = MaterialTheme.typography.bodyMedium,
                                color = MaterialTheme.colorScheme.onSurfaceVariant
                            )
                        }
                    }
                } else {
                    val gridBorderColor = MaterialTheme.colorScheme.outline
                    val boxBorderColor = MaterialTheme.colorScheme.primary
                    Column(modifier = Modifier.fillMaxSize()) {
                        for (r in 0..8) {
                            Row(modifier = Modifier.weight(1f).fillMaxWidth()) {
                                for (c in 0..8) {
                                    val value = board[r][c]
                                    val isGiven = generated.puzzle[r][c] != 0
                                    val isSelected = selectedCell == (r to c)
                                    val selectedVal = selectedCell?.let { (sr, sc) -> board[sr][sc] } ?: 0
                                    val isPeer = selectedCell?.let { (sr, sc) ->
                                        sr == r || sc == c || (sr / 3 == r / 3 && sc / 3 == c / 3)
                                    } ?: false
                                    val sameValue = selectedVal != 0 && value == selectedVal
                                    val isMistake = value != 0 && value != generated.solution[r][c]
                                    val cage = cageByCell[r to c]
                                    val cageSum = cageLabelCell[r to c]

                                    val cellBg = when {
                                        isSelected -> MaterialTheme.colorScheme.primary.copy(alpha = 0.28f)
                                        sameValue -> MaterialTheme.colorScheme.primary.copy(alpha = 0.16f)
                                        isPeer -> MaterialTheme.colorScheme.surfaceVariant
                                        isKiller && cage != null && cage.id % 2 == 1 -> MaterialTheme.colorScheme.surfaceVariant.copy(alpha = 0.45f)
                                        else -> MaterialTheme.colorScheme.surface
                                    }

                                    Box(
                                        modifier = Modifier
                                            .weight(1f)
                                            .aspectRatio(1f)
                                            .background(cellBg)
                                            .drawBehind {
                                                val thin = 1f
                                                val thick = 3.5f
                                                if (c < 8) {
                                                    drawLine(
                                                        color = if (c % 3 == 2) boxBorderColor else gridBorderColor,
                                                        start = Offset(size.width, 0f),
                                                        end = Offset(size.width, size.height),
                                                        strokeWidth = if (c % 3 == 2) thick else thin
                                                    )
                                                }
                                                if (r < 8) {
                                                    drawLine(
                                                        color = if (r % 3 == 2) boxBorderColor else gridBorderColor,
                                                        start = Offset(0f, size.height),
                                                        end = Offset(size.width, size.height),
                                                        strokeWidth = if (r % 3 == 2) thick else thin
                                                    )
                                                }
                                            }
                                            .clickable { selectedCell = r to c },
                                        contentAlignment = Alignment.Center
                                    ) {
                                        if (cageSum != null) {
                                            Text(
                                                text = cageSum.toString(),
                                                fontSize = 8.sp,
                                                fontFamily = JetBrainsMonoFontFamily,
                                                color = MaterialTheme.colorScheme.onSurfaceVariant,
                                                modifier = Modifier
                                                    .align(Alignment.TopStart)
                                                    .padding(start = 2.dp, top = 1.dp)
                                            )
                                        }
                                        if (value != 0) {
                                            Text(
                                                text = value.toString(),
                                                fontSize = 18.sp,
                                                fontFamily = JetBrainsMonoFontFamily,
                                                fontWeight = if (isGiven) FontWeight.Bold else FontWeight.Medium,
                                                color = when {
                                                    isMistake -> Color(0xFFEF5350)
                                                    isGiven -> MaterialTheme.colorScheme.onSurface
                                                    else -> MaterialTheme.colorScheme.primary
                                                },
                                                modifier = Modifier.springPop(if (!isGiven) value else null, popScale = 1.25f)
                                            )
                                        } else if (notes[r][c].isNotEmpty()) {
                                            Text(
                                                text = notes[r][c].sorted().joinToString(" "),
                                                fontSize = 8.sp,
                                                lineHeight = 9.sp,
                                                fontFamily = JetBrainsMonoFontFamily,
                                                color = MaterialTheme.colorScheme.onSurfaceVariant,
                                                modifier = Modifier.padding(2.dp)
                                            )
                                        }
                                    }
                                }
                            }
                        }
                    }
                }
            }
        }

        Spacer(modifier = Modifier.height(10.dp))

        // Tools Row: Notes, Erase, Hint
        Row(
            modifier = Modifier.fillMaxWidth(),
            horizontalArrangement = Arrangement.spacedBy(8.dp)
        ) {
            OutlinedButton(
                onClick = { noteMode = !noteMode },
                modifier = Modifier.weight(1f).height(46.dp),
                shape = RoundedCornerShape(12.dp),
                border = BorderStroke(if (noteMode) 1.5.dp else 1.dp, if (noteMode) MaterialTheme.colorScheme.primary else MaterialTheme.colorScheme.outline)
            ) {
                Icon(Icons.Rounded.Edit, contentDescription = null, modifier = Modifier.size(16.dp))
                Spacer(Modifier.width(6.dp))
                Text(if (noteMode) "Notes ON" else "Notes", style = MaterialTheme.typography.labelLarge)
            }
            OutlinedButton(
                onClick = ::eraseCell,
                modifier = Modifier.weight(1f).height(46.dp),
                shape = RoundedCornerShape(12.dp)
            ) {
                Icon(Icons.Rounded.Backspace, contentDescription = null, modifier = Modifier.size(16.dp))
                Spacer(Modifier.width(6.dp))
                Text("Erase", style = MaterialTheme.typography.labelLarge)
            }
            OutlinedButton(
                onClick = ::applyHint,
                modifier = Modifier.weight(1f).height(46.dp),
                shape = RoundedCornerShape(12.dp)
            ) {
                Icon(Icons.Rounded.Lightbulb, contentDescription = null, modifier = Modifier.size(16.dp))
                Spacer(Modifier.width(6.dp))
                Text("Hint", style = MaterialTheme.typography.labelLarge)
            }
        }

        Spacer(modifier = Modifier.height(8.dp))

        // Number Input Pad (1-9)
        Row(
            modifier = Modifier.fillMaxWidth(),
            horizontalArrangement = Arrangement.spacedBy(4.dp)
        ) {
            (1..9).forEach { digit ->
                val remaining = 9 - board.sumOf { row -> row.count { it == digit } }
                Surface(
                    modifier = Modifier
                        .weight(1f)
                        .height(52.dp)
                        .bouncyPress(enabled = remaining > 0 || noteMode)
                        .clickable(enabled = remaining > 0 || noteMode) { placeDigit(digit) },
                    shape = RoundedCornerShape(10.dp),
                    color = MaterialTheme.colorScheme.surfaceVariant,
                    border = BorderStroke(1.dp, MaterialTheme.colorScheme.outline)
                ) {
                    Column(
                        modifier = Modifier.fillMaxSize(),
                        horizontalAlignment = Alignment.CenterHorizontally,
                        verticalArrangement = Arrangement.Center
                    ) {
                        Text(
                            text = digit.toString(),
                            style = MaterialTheme.typography.titleLarge.copy(fontFamily = JetBrainsMonoFontFamily),
                            color = if (remaining <= 0 && !noteMode) MaterialTheme.colorScheme.onSurfaceVariant.copy(alpha = 0.4f) else MaterialTheme.colorScheme.onSurface
                        )
                        Text(
                            text = remaining.coerceAtLeast(0).toString(),
                            fontSize = 9.sp,
                            fontFamily = JetBrainsMonoFontFamily,
                            color = MaterialTheme.colorScheme.onSurfaceVariant
                        )
                    }
                }
            }
        }
    }

    if (solved) {
        GameCompletionDialog(
            title = "${game.title} Solved!",
            subtitle = "Completed in %02d:%02d with $mistakes mistakes.".format(elapsedSeconds / 60, elapsedSeconds % 60),
            onPlayAgain = ::restart,
            onExit = onBack
        )
    }
}
